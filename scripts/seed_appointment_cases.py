"""Replace a PawPals JSON data file with appointment-display test cases."""

import argparse
import json
import shutil
from datetime import datetime, timedelta, timezone
from pathlib import Path


def date_text(value):
    return value.strftime("%d-%m-%Y")


def appointment(day, time, details, pets, end_time=None):
    result = {"date": date_text(day), "time": time, "details": details}
    if end_time is not None:
        result["endTime"] = end_time
    if pets:
        result["pets"] = pets
    return result


def session(day, time, details, pets, notes, logged_at):
    end_time = (datetime.strptime(time, "%H:%M") + timedelta(hours=1)).strftime("%H:%M")
    return {
        "appointment": appointment(day, time, details, pets, end_time),
        "notes": notes,
        "loggedAt": logged_at.astimezone(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z"),
    }


def validate_appointments(data):
    for client in data["clients"]:
        appointments = list(client.get("appointments", []))
        appointments.extend(item["appointment"] for item in client.get("history", []))
        for item in appointments:
            end_time = item.get("endTime")
            if end_time is not None and end_time <= item["time"]:
                raise ValueError(f"End time must be after start time: {item}")


def build_data(now):
    today = now.date()
    if now.hour >= 10:
        active_start = now.replace(minute=0, second=0, microsecond=0) - timedelta(hours=1)
    else:
        active_start = (now - timedelta(days=1)).replace(hour=8, minute=0, second=0, microsecond=0)
    yesterday = today - timedelta(days=1)
    tomorrow = today + timedelta(days=1)
    next_week = today + timedelta(days=7)
    two_weeks = today + timedelta(days=14)

    history = [
        session(today - timedelta(days=1), "09:00", "Full groom", ["Milo"],
                "Calm throughout the session", now - timedelta(days=1)),
        session(today - timedelta(days=3), "14:00", "Nail trim", ["Luna"],
                "Used the quiet dryer", now - timedelta(days=3)),
        session(today - timedelta(days=7), "10:30", "Bath and brush", ["Milo", "Luna"],
                "No issues observed", now - timedelta(days=7)),
        session(today - timedelta(days=14), "16:00", "Ear cleaning", ["Milo"],
                "Owner requested a shorter session", now - timedelta(days=14)),
    ]

    return {
        "_comment": "Generated by scripts/seed_appointment_cases.py for UI inspection.",
        "clients": [
            {
                "name": "Appointment Display Case",
                "phone": "91234567",
                "email": "appointments@example.com",
                "address": "1 Example Street",
                "tags": ["ui-test"],
                "pets": [
                    {"name": "Milo", "species": "Dog", "breed": "Toy Poodle"},
                    {"name": "Luna", "species": "Cat", "breed": "Persian"},
                ],
                "appointments": [
                    appointment(yesterday, "09:00", "Overdue appointment", ["Milo"], "10:00"),
                    appointment(active_start.date(), active_start.strftime("%H:%M"),
                                "Started appointment", ["Luna"],
                                (active_start + timedelta(hours=1)).strftime("%H:%M")),
                    appointment(today, "23:00", "Later today", ["Milo"], "23:30"),
                    appointment(tomorrow, "10:00", "Tomorrow", ["Milo", "Luna"], "11:30"),
                    appointment(next_week, "14:00", "Next week", ["Luna"]),
                    appointment(two_weeks, "16:30", "Far future", ["Milo"]),
                ],
                "history": history,
            },
            {
                "name": "Compact Upcoming Case",
                "phone": "92345678",
                "email": "upcoming@example.com",
                "address": "2 Example Street",
                "tags": ["ui-test"],
                "pets": [{"name": "Coco", "species": "Dog", "breed": "Poodle"}],
                "appointments": [
                    appointment(tomorrow, "09:00", "", ["Coco"]),
                    appointment(tomorrow, "11:00", "", ["Coco"]),
                    appointment(tomorrow, "13:00", "", ["Coco"]),
                    appointment(tomorrow, "15:00", "Hidden fourth appointment", ["Coco"]),
                ],
            },
            {
                "name": "History Overflow Case",
                "phone": "93456789",
                "email": "history@example.com",
                "address": "3 Example Street",
                "tags": ["ui-test"],
                "pets": [{"name": "Bailey", "species": "Dog", "breed": "Beagle"}],
                "appointments": [],
                "history": [
                    session(today - timedelta(days=2), "09:00", "Groom", ["Bailey"],
                            "A long note to check how wrapped history text affects the card layout", now),
                    session(today - timedelta(days=4), "09:00", "Bath", ["Bailey"], "Short note", now),
                    session(today - timedelta(days=6), "09:00", "Brush", ["Bailey"], "Short note", now),
                    session(today - timedelta(days=8), "09:00", "Nails", ["Bailey"], "Short note", now),
                ],
            },
        ],
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("path", nargs="?", default="data/pawpals.json",
                        help="PawPals JSON file to replace (default: data/pawpals.json)")
    parser.add_argument("--no-backup", action="store_true",
                        help="Do not create a .bak copy before replacing the file")
    args = parser.parse_args()

    path = Path(args.path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and not args.no_backup:
        backup = path.with_suffix(path.suffix + ".before-appointment-cases.bak")
        shutil.copy2(path, backup)
        print(f"Backup written to {backup}")

    data = build_data(datetime.now().astimezone())
    validate_appointments(data)
    temporary_path = path.with_suffix(path.suffix + ".tmp")
    temporary_path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    temporary_path.replace(path)
    print(f"Wrote appointment cases to {path}")


if __name__ == "__main__":
    main()
